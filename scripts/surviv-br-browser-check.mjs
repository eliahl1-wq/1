// Run with the local-only fixture server and Vite on 5174 (API on 5057).
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const api = 'http://127.0.0.1:5057';
const origin = 'http://127.0.0.1:5174';
const fixture = () => fetch(`${api}/fixture`).then(response => response.json());
const act = action => fetch(`${api}/fixture/${action}`, { method: 'POST' });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
const output = resolve('.local/surviv-br-playtest');
await mkdir(output, { recursive: true });
const errors = [];
try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5 });
    // Keep the fixture isolated even if site analytics/background integrations load.
    await context.route('**/*', route => {
        const url = new URL(route.request().url());
        return ['127.0.0.1', 'localhost'].includes(url.hostname) ? route.continue() : route.abort();
    });
    const { token, payouts: initialPayouts } = await fixture();
    await context.addInitScript(value => {
        localStorage.setItem('token', value);
        localStorage.setItem('selected_gamemode', 'br-surviv');
        localStorage.setItem('selected_entry_fee', '5');
        localStorage.setItem('hide_player_names', 'false');
    }, token);
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${origin}/surviv-battle-royale`);
    await page.getByText('Battle Royale · 10–25', { exact: true }).first().waitFor();
    if (process.env.CHECK_FREE_BR === '1') {
        const preview = page.locator('img[src="/surviv-battle-royale-gameplay.png"]').first();
        await preview.waitFor();
        assert.ok(await preview.evaluate(img => img.complete && img.naturalWidth > 0));
        await page.locator('label.free-mode-option').click();
        assert.equal(await page.getByRole('checkbox', { name: 'Free play', exact: true }).isChecked(), true);
        await page.waitForTimeout(300);
        assert.equal(await page.evaluate(() => localStorage.getItem('public_free_mode')), 'true');
        await page.screenshot({ path: resolve(output, 'free-pregame.png') });
        await page.goto(`${origin}/br-lobby`);
        await page.getByText('Waiting for 9 more players to start', { exact: true }).waitFor();
        await page.waitForTimeout(2000);
        assert.ok(page.url().endsWith('/br-lobby'), 'bots do not start immediately');
        await page.screenshot({ path: resolve(output, 'free-queue.png') });
        await page.waitForURL('**/surviv-game', { timeout: 30000 });
        await page.locator('.sbr-countdown').waitFor({ state: 'detached', timeout: 10000 });
        await page.locator('.sbr-zone-status').waitFor();
        assert.equal((await page.locator('.sbr-survivors strong').innerText()).trim(), '10');
        await page.screenshot({ path: resolve(output, 'free-bots-game.png') });
        assert.deepEqual(errors, []);
        console.log('Free BR browser flow passed: gameplay image, free toggle, delayed solo bot fill, actual game.');
    } else {
    await page.screenshot({ path: resolve(output, 'pregame.png') });
    await page.goto(`${origin}/br-lobby`);
    await page.getByText('Waiting for 9 more players to start', { exact: true }).waitFor();
    await page.screenshot({ path: resolve(output, 'queue.png') });
    await act('fill');
    await page.waitForURL('**/surviv-game', { timeout: 30000 });
    await page.locator('.sbr-countdown').waitFor();
    await page.screenshot({ path: resolve(output, 'countdown.png') });
    const frozen = (await fixture()).player;
    await page.keyboard.down('d');
    await page.waitForTimeout(250);
    await page.keyboard.up('d');
    const still = (await fixture()).player;
    assert.equal(still.x, frozen.x, 'no movement during countdown');
    await page.locator('.sbr-countdown').waitFor({ state: 'detached', timeout: 10000 });
    await page.locator('.sbr-zone-status').waitFor();
    const before = (await fixture()).player;
    await page.keyboard.down('d');
    await page.waitForTimeout(550);
    await page.keyboard.up('d');
    const after = (await fixture()).player;
    assert.ok(Math.hypot(after.x - before.x, after.y - before.y) > 10, 'real authoritative movement');
    assert.equal(await page.getByText('Cash Out', { exact: true }).count(), 0);
    await act('loot');
    await page.waitForTimeout(400);
    await page.keyboard.press('f');
    await page.waitForTimeout(500);
    assert.equal((await fixture()).player.weapon, 'm416', 'normal weapon pickup works inside BR');
    await page.mouse.move(1030, 450);
    await page.mouse.down();
    await page.waitForTimeout(350);
    await page.mouse.up();
    assert.ok((await fixture()).player.ammo < 30, 'real firing consumes server magazine');
    await page.screenshot({ path: resolve(output, 'in-game.png') });
    await page.keyboard.press('m');
    await page.getByRole('dialog', { name: 'Full match map' }).waitFor();
    await page.screenshot({ path: resolve(output, 'safe-zone-map.png') });
    await page.keyboard.press('m');
    await page.reload();
    await page.locator('.sbr-zone-status').waitFor();
    assert.equal((await fixture()).active, 1, 'refresh resumes rather than joining a second match');
    await page.setViewportSize({ width: 844, height: 390 });
    await page.screenshot({ path: resolve(output, 'compact-in-game.png') });
    await act('finish');
    await page.getByRole('heading', { name: 'LAST SURVIVOR' }).waitFor();
    await page.getByText('Test match — no real money paid.', { exact: true }).waitFor();
    await page.waitForTimeout(400);
    await page.screenshot({ path: resolve(output, 'victory-compact.png') });
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.waitForTimeout(300);
    await page.screenshot({ path: resolve(output, 'victory.png') });
    assert.equal((await fixture()).payouts, initialPayouts + 1);
    await page.getByRole('button', { name: 'Find another match', exact: true }).click();
    await page.getByText('Waiting for 9 more players to start', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Cancel Search', exact: true }).click();
    await context.close();
    const mobile = await browser.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
    await mobile.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
    await mobile.addInitScript(value => {
        localStorage.setItem('token', value); localStorage.setItem('selected_gamemode', 'br-surviv'); localStorage.setItem('selected_entry_fee', '5');
    }, token);
    const touch = await mobile.newPage();
    touch.on('pageerror', error => errors.push(error.message));
    await touch.goto(`${origin}/br-lobby`);
    await touch.getByText('Waiting for 9 more players to start', { exact: true }).waitFor();
    await touch.screenshot({ path: resolve(output, 'mobile-queue.png') });
    await act('fill');
    await touch.waitForURL('**/surviv-game', { timeout: 30000 });
    await touch.locator('.sbr-countdown').waitFor();
    await touch.locator('.sbr-countdown').waitFor({ state: 'detached', timeout: 10000 });
    await touch.locator('.sbr-zone-status').waitFor();
    assert.equal(await touch.locator('.game-viewport--mobile').count(), 1);
    assert.equal(await touch.getByRole('progressbar', { name: 'Health', exact: true }).isVisible(), false);
    assert.equal(await touch.getByRole('button', { name: 'Take', exact: true }).count(), 0);
    await touch.waitForTimeout(500);
    await touch.screenshot({ path: resolve(output, 'mobile-in-game.png') });
    await act('defeat');
    await touch.getByRole('heading', { name: 'ELIMINATED', exact: true }).waitFor();
    assert.equal((await touch.locator('.sbr-placement').innerText()).replace(/\s/g, ''), '#10');
    await touch.waitForTimeout(400);
    await touch.screenshot({ path: resolve(output, 'mobile-eliminated.png') });
    await touch.getByRole('button', { name: 'Back to lobby', exact: true }).click();
    await touch.waitForURL('**/pre-game');
    assert.deepEqual(errors, [], 'no browser runtime exceptions');
    console.log(JSON.stringify({ passed: true, scenarios: ['public selection', '10-player queue', 'locked countdown', 'movement', 'pickup', 'firing', 'safe-zone map', 'rejoin', 'victory payout', 'queue again'], screenshots: output }, null, 2));
    }
} finally { await browser.close(); }
